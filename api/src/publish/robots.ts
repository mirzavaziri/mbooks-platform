import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pool } from '../db/pool.js';

// Crawlers that collect text for training or answering with AI models.
// Search engines are not listed here: a book that opts out of them too
// carries <meta name="robots" content="noindex, ..."> instead (page.ts),
// which only works if they are still allowed to fetch the page.
const AI_CRAWLERS = [
  'GPTBot',
  'ChatGPT-User',
  'OAI-SearchBot',
  'ClaudeBot',
  'Claude-Web',
  'anthropic-ai',
  'Google-Extended',
  'CCBot',
  'PerplexityBot',
  'Bytespider',
  'Applebot-Extended',
  'meta-externalagent',
  'Amazonbot',
  'cohere-ai',
  'Diffbot',
  'Omgilibot',
  'Timpibot',
];

// Rewrites <publish dir>/robots.txt from the books whose settings say
// crawlers: "block" (book_settings.data). Called after every publish, so
// the file always matches the current settings.
export async function writeRobotsTxt(publishDir: string): Promise<string[]> {
  const { rows } = await pool.query(
    `select b.slug from books b join book_settings bs on bs.book_id = b.id
      where b.deleted_at is null and bs.data->>'crawlers' = 'block' order by b.slug`,
  );
  const slugs: string[] = rows.map((r: { slug: string }) => r.slug);
  const lines = ['# Generated by the mbooks publish step; edits here are overwritten.', ''];
  if (slugs.length) {
    for (const ua of AI_CRAWLERS) lines.push(`User-agent: ${ua}`);
    for (const s of slugs) lines.push(`Disallow: /${s}/`);
    lines.push('');
  }
  lines.push('User-agent: *', 'Allow: /', '');
  writeFileSync(join(publishDir, 'robots.txt'), lines.join('\n'), 'utf8');
  return slugs;
}
